          while (i < s.length && /[0-9]/.test(s[i])) num += s[i++];
          const mult = num === '' ? 1 : parseInt(num, 10);
          for (const el in inner.counts) counts[el] = (counts[el] || 0) + inner.counts[el] * mult;
