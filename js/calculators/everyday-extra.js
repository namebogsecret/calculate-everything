/* На каждый день (расширение): даты, возраст, рабочие дни, возраст питомца. */
(function () {
  const F = (x, d) => window.CE.fmt(x, d);
  function fmtDate(ms){ const d=new Date(ms); const p=n=>String(n).padStart(2,'0'); return p(d.getUTCDate())+'.'+p(d.getUTCMonth()+1)+'.'+d.getUTCFullYear(); }

  window.CE.register('everyday', [
    {
      id: 'age-calc', title: 'Калькулятор возраста', title_en: 'Age Calculator',
      desc: 'Точный возраст в годах, месяцах и днях по дате рождения.',
      tags: ['возраст', 'дата рождения', 'сколько лет', 'age', 'birthday', 'возраст по дате рождения'],
      inputs: [
        { key: 'birth', label: 'Дата рождения (ГГГГ-ММ-ДД)', placeholder: '1990-05-20' },
      ],
      compute(v) {
        const s = (document.getElementById('in_birth') || {}).value;
        if (!s) return { note: 'Введите дату в формате ГГГГ-ММ-ДД.' };
        const tb = Date.parse(s);
        if (Number.isNaN(tb)) return { error: 'Не удалось распознать дату. Формат: 1990-05-20.' };
        const now = new Date();
        const today = Date.UTC(now.getFullYear(), now.getMonth(), now.getDate());
        if (tb > today) return { error: 'Дата рождения в будущем — проверьте ввод.' };
        const b = new Date(tb);
        const by = b.getUTCFullYear(), bm = b.getUTCMonth(), bd = b.getUTCDate();
        const t = new Date(today);
        const ty = t.getUTCFullYear(), tm = t.getUTCMonth(), td = t.getUTCDate();
        // полные годы/месяцы/дни с заёмами
        let years = ty - by, months = tm - bm, days = td - bd;
        if (days < 0) {
          months -= 1;
          // дней в предыдущем месяце относительно сегодняшней даты
          const prevMonthDays = new Date(Date.UTC(ty, tm, 0)).getUTCDate();
          days += prevMonthDays;
        }
        if (months < 0) { years -= 1; months += 12; }
        const totalDays = Math.round((today - tb) / 86400000);
        // следующий день рождения
        let nb = Date.UTC(ty, bm, bd);
        if (nb < today) nb = Date.UTC(ty + 1, bm, bd);
        const untilNext = Math.round((nb - today) / 86400000);
        const ageText = years + ' лет ' + months + ' мес ' + days + ' дн';
        return {
          outputs: [
            { label: 'Возраст', text: ageText, primary: true },
            { label: 'Всего прожито дней', value: totalDays },
            { label: 'До следующего дня рождения', value: untilNext, unit: 'дн' },
          ],
          formula: 'Возраст = сегодня − дата рождения (с заёмом дней и месяцев)',
          note: 'Дата рождения: ' + fmtDate(tb) + ' · сегодня: ' + fmtDate(today) + '.',
        };
      },
      explain: '<p>Возраст считается вычитанием даты рождения из сегодняшней даты с «заёмом»: сначала годы, затем месяцы, затем дни (при нехватке дней занимаем из месяца, при нехватке месяцев — из года). Формат ввода — ГГГГ-ММ-ДД.</p>',
      faq: [
        { q: 'Почему возраст не совпадает с простым вычитанием годов?', a: '<p>Если день рождения в этом году ещё не наступил, полный год ещё не «закрыт», поэтому из разницы годов вычитается единица — отсюда месяцы и дни остатка.</p>' },
        { q: 'Учитываются ли високосные годы?', a: '<p>Да. Расчёт идёт по реальным датам через календарь, поэтому 29 февраля и разная длина месяцев учтены автоматически.</p>' },
        { q: 'Что показывает «всего прожито дней»?', a: '<p>Это полное число суток между датой рождения и сегодняшним днём — удобно для круглых дат вроде 10 000 дней.</p>' },
      ],
    },
    {
      id: 'days-until', title: 'Сколько дней до даты', title_en: 'Days Until',
      desc: 'Сколько дней, недель и месяцев осталось до события.',
      tags: ['сколько дней до', 'дни до', 'обратный отсчёт', 'days until', 'countdown', 'до нового года'],
      inputs: [
        { key: 'target', label: 'Целевая дата (ГГГГ-ММ-ДД)', placeholder: '2026-12-31' },
      ],
      compute(v) {
        const s = (document.getElementById('in_target') || {}).value;
        if (!s) return { note: 'Введите дату в формате ГГГГ-ММ-ДД.' };
        const tt = Date.parse(s);
        if (Number.isNaN(tt)) return { error: 'Не удалось распознать дату. Формат: 2026-12-31.' };
        const now = new Date();
        const today = Date.UTC(now.getFullYear(), now.getMonth(), now.getDate());
        const days = Math.round((tt - today) / 86400000);
        const ad = Math.abs(days);
        let note;
        if (days < 0) note = 'Дата уже прошла (' + ad + ' дней назад).';
        else if (days === 0) note = 'Это сегодня!';
        return {
          outputs: [
            { label: 'Дней', value: ad, primary: true },
            { label: 'Недель', value: ad / 7, digits: 1 },
            { label: 'Месяцев (≈30.44 дн)', value: ad / 30.44, digits: 1 },
          ],
          formula: 'Дней = целевая дата − сегодня',
          note: note,
        };
      },
      explain: '<p>Калькулятор считает количество суток между сегодняшним днём и выбранной датой. Недели и месяцы — производные оценки (÷7 и ÷30.44). Если дата уже прошла, показывается, сколько дней назад это было.</p>',
      faq: [
        { q: 'Считается ли сегодняшний день?', a: '<p>Нет, считается разница в полных сутках. Если целевая дата — сегодня, результат 0 дней и подпись «Это сегодня!».</p>' },
        { q: 'Можно ли посчитать, сколько дней до Нового года?', a: '<p>Да — введите 31 декабря текущего года или 1 января следующего, и калькулятор покажет остаток.</p>' },
        { q: 'Почему месяцев дробное число?', a: '<p>Месяц берётся усреднённым (30.44 дня = 365.25 ÷ 12), поэтому результат в месяцах почти всегда нецелый — это ориентир, а точная величина — в днях.</p>' },
      ],
    },
    {
      id: 'working-days', title: 'Рабочие дни между датами', title_en: 'Working Days',
      desc: 'Количество рабочих и выходных дней в периоде.',
      tags: ['рабочие дни', 'будни', 'выходные', 'working days', 'business days', 'период'],
      inputs: [
        { key: 'd1', label: 'Дата начала (ГГГГ-ММ-ДД)', placeholder: '2026-01-01' },
        { key: 'd2', label: 'Дата конца (ГГГГ-ММ-ДД)', placeholder: '2026-01-31' },
      ],
      compute(v) {
        const s1 = (document.getElementById('in_d1') || {}).value;
        const s2 = (document.getElementById('in_d2') || {}).value;
        if (!s1 || !s2) return { note: 'Введите обе даты в формате ГГГГ-ММ-ДД.' };
        const t1 = Date.parse(s1), t2 = Date.parse(s2);
        if (Number.isNaN(t1) || Number.isNaN(t2)) return { error: 'Не удалось распознать дату. Формат: 2026-01-31.' };
        const start = Math.min(t1, t2), end = Math.max(t1, t2);
        const totalDays = Math.round((end - start) / 86400000) + 1; // обе границы включительно
        if (totalDays > 40000) return { note: 'Слишком большой диапазон. Выберите период покороче (до ~100 лет).' };
        let work = 0, weekend = 0;
        for (let ms = start; ms <= end; ms += 86400000) {
          const dow = new Date(ms).getUTCDay();
          if (dow === 0 || dow === 6) weekend++; else work++;
        }
        return {
          outputs: [
            { label: 'Рабочих дней', value: work, primary: true },
            { label: 'Выходных (сб+вс)', value: weekend },
            { label: 'Всего дней', value: totalDays },
          ],
          formula: 'Перебор всех дней периода (обе границы включительно); день рабочий, если это не сб и не вс',
          steps: ['Период: ' + fmtDate(start) + ' — ' + fmtDate(end) + ', обе даты включены (' + totalDays + ' дн).', 'Каждый день проверяется: суббота и воскресенье → выходной, иначе → рабочий.'],
          note: 'Без учёта государственных праздников и переносов.',
        };
      },
      explain: '<p>Калькулятор перебирает все дни периода (включая обе граничные даты) и относит к рабочим все дни, кроме субботы и воскресенья. Праздники и переносы выходных не учитываются — их состав зависит от страны и года.</p>',
      faq: [
        { q: 'Включаются ли начальная и конечная даты?', a: '<p>Да, обе границы входят в период. Например, с 1 по 5 число — это 5 дней, а не 4.</p>' },
        { q: 'Учитываются ли праздники?', a: '<p>Нет. Считаются только календарные выходные (сб и вс). Государственные праздники и переносы рабочих дней нужно вычитать отдельно — они зависят от страны.</p>' },
        { q: 'Что если даты перепутаны местами?', a: '<p>Ничего страшного: калькулятор сам берёт меньшую дату как начало, а большую — как конец.</p>' },
      ],
    },
    {
      id: 'pet-age', title: 'Возраст собаки или кошки по-человечески', title_en: 'Pet Age',
      desc: 'Перевод возраста питомца в «человеческие» годы.',
      tags: ['возраст собаки', 'возраст кошки', 'питомец', 'по человеческим меркам', 'pet age', 'dog years', 'cat years'],
      inputs: [
        { key: 'animal', label: 'Питомец', options: [{ value: 'dog', label: '🐕 Собака' }, { value: 'cat', label: '🐈 Кошка' }], default: 'dog' },
        { key: 'age', label: 'Возраст питомца', unit: 'лет', default: 3 },
        { key: 'size', label: 'Размер собаки', options: [{ value: 'small', label: 'Мелкая (до 10 кг)' }, { value: 'medium', label: 'Средняя (10–25 кг)' }, { value: 'large', label: 'Крупная (более 25 кг)' }], default: 'medium' },
      ],
      compute(v) {
        if (Number.isNaN(v.age) || v.age < 0) return { note: 'Введите возраст питомца в годах.' };
        const age = v.age;
        let human, hint, note;
        if (v.animal === 'cat') {
          human = age <= 1 ? age * 15 : age <= 2 ? 15 + (age - 1) * 9 : 24 + (age - 2) * 4;
          hint = 'Кошки взрослеют очень быстро в первые 2 года, потом стареют плавно (+4 «человеческих» года в год).';
          note = 'Для кошек размер не учитывается.';
        } else {
          if (v.size === 'small') {
            human = age <= 1 ? 15 : age <= 2 ? 24 : 24 + (age - 2) * 4;
            hint = 'Мелкие собаки живут дольше и стареют медленнее крупных.';
          } else if (v.size === 'large') {
            human = age <= 1 ? 15 : age <= 2 ? 22 : 22 + (age - 2) * 6;
            hint = 'Крупная собака стареет быстрее — каждый её год идёт примерно за 6 человеческих.';
          } else {
            human = age <= 1 ? 15 : age <= 2 ? 24 : 24 + (age - 2) * 5;
            hint = 'Средняя собака: первые 2 года = 24 человеческих, дальше примерно +5 в год.';
          }
        }
        return {
          outputs: [
            { label: 'Человеческий возраст', value: Math.round(human), unit: 'лет', primary: true },
            { label: 'Пояснение', text: hint },
          ],
          formula: '1-й год ≈ 15, 2-й год добавляет ещё ~9, дальше фиксированная прибавка за каждый год',
          note: note,
        };
      },
      explain: '<p>Возраст питомца переводится в «человеческий» по ветеринарной аппроксимации: животные стремительно взрослеют в первые два года, затем стареют равномерно. У собак скорость зависит от размера — крупные стареют быстрее. У кошек размер не влияет. Это весёлая прикидка для разговора, а не точная биология — поделитесь результатом с друзьями!</p>',
      faq: [
        { q: 'Правда ли, что 1 год собаки = 7 человеческих?', a: '<p>Это устаревший миф. На деле первый год даёт сразу ~15 человеческих лет, а дальше скорость старения зависит от размера породы — поэтому «×7» сильно упрощает картину.</p>' },
        { q: 'Почему для кошки не нужен размер?', a: '<p>Кошки гораздо однороднее собак по размеру и продолжительности жизни, поэтому для них используется единая шкала без поправки на вес.</p>' },
        { q: 'Почему крупные собаки «старше»?', a: '<p>У больших пород короче продолжительность жизни и быстрее обмен веществ, поэтому каждый их календарный год соответствует большему числу человеческих лет.</p>' },
        { q: 'Насколько это точно?', a: '<p>Это популярная приближённая модель. Реальный «возраст» зависит от породы, генетики и здоровья, а современные эпигенетические шкалы дают другую кривую. Для развлечения — отлично, для медицины — нет.</p>' },
      ],
    },
  ]);
})();
